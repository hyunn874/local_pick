function normalizeKeyword(value) {
  return String(value || '').replace(/\s/g, '').toLowerCase();
}

export function findRegionSearchMatch(keyword, regions = []) {
  const normalizedKeyword = normalizeKeyword(keyword);

  if (!normalizedKeyword) {
    return null;
  }

  const regionMatch = regions.find((region) => {
    const fullName = normalizeKeyword(region.fullName || `${region.sidoName || ''}${region.sigunguName || ''}`);
    const sigunguName = normalizeKeyword(region.sigunguName);

    return normalizedKeyword === fullName || normalizedKeyword === sigunguName;
  });

  if (regionMatch) {
    return {
      sidoName: regionMatch.sidoName,
      sigunguName: regionMatch.sigunguName,
      regionCode: regionMatch.regionCode,
      fullName: regionMatch.fullName || `${regionMatch.sidoName} ${regionMatch.sigunguName}`,
      latitude: Number(regionMatch.centerLatitude),
      longitude: Number(regionMatch.centerLongitude),
    };
  }

  return REGION_SEARCH_MAP.find((region) => {
    const fullName = normalizeKeyword(region.fullName);
    const sigunguName = normalizeKeyword(region.sigunguName);

    return normalizedKeyword === fullName || normalizedKeyword === sigunguName;
  }) || null;
}
